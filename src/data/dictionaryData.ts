function capitalizeFirstLetter(val: string): string {
  if (!val) return '';
  return val.charAt(0).toUpperCase() + val.slice(1);
}

function stripUzbekAffixes(word: string): string {
  let w = word.toLowerCase().trim();
  const affixes = [
    'larimizdan', 'laringizdan', 'larimizni', 'laringizni', 'larimizga', 'laringizga',
    'larimizda', 'laringizda', 'larimiz', 'laringiz', 'lardan', 'larga', 'larni', 'larda',
    'larning', 'mizdan', 'ngizdan', 'mizga', 'ngizga', 'mizda', 'ngizda', 'imiz', 'ingiz',
    'dan', 'gan', 'kan', 'qan', 'moq', 'ish', 'lik', 'siz', 'ning', 'ing', 'im', 'ni', 'ga', 'ka', 'qa', 'da', 'lar'
  ];

  for (const aff of affixes) {
    if (w.length > aff.length + 2 && w.endsWith(aff)) {
      w = w.slice(0, -aff.length);
      break;
    }
  }
  return w;
}

